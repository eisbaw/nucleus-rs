//! Family: multi-COMPUTE-worker partitioned elementwise map.
//!
//! Owned by TASK-0453.01.01 (cross-referenced from TASK-0455.05). The
//! original subclass only ever crossed a SINGLE host→w0 boundary; this
//! family places a pure scalar map on `{ w0, w1, ... }` and partitions the
//! outer loop with `partition=workers`, so the generated program stresses
//! the distributed transfer-inject path (1-to-N scatter of the input,
//! N-to-1 gather of the result) the curated corpus exercises with
//! 03-reduction / 06-separable-filter.
//!
//! Shape (modelled on 03-reduction's 2-D partition-axis layout): a 2-D
//! `a : i32[NW][PS]` whose OUTER axis is the partition axis. Each compute
//! worker `w` owns one row and maps every element with a 1..=3-stage pure
//! scalar pipeline. No cross-row dependency (no halo) — the simplest
//! multi-worker shape, so it is provably 7-backend bit-identical (verified
//! by hand on pthreads-sync + mp-tcp-bufsync before landing).
//!
//! Determinism / correctness: a pure elementwise map has NO order
//! dependence across workers, so the partitioned emit equals the
//! sequential reference regardless of worker count.

use std::fmt::Write as _;

use super::io_scaffold;
use crate::op::Op;
use crate::program::{push_i32_le, SourceBundle};
use crate::rng::Rng;

#[derive(Clone, Debug)]
pub(crate) struct PartitionWorkers {
    /// Compute-worker count == outer-axis length (one row per worker).
    nw: usize,
    /// Per-worker partition width (inner-axis length).
    ps: usize,
    /// 1..=3 pure scalar stages applied left-to-right per element.
    stages: Vec<Op>,
    /// Flat row-major primary input, `nw * ps` words.
    a: Vec<i32>,
    /// Flat row-major SECOND operand, `nw * ps` words. Every stage folds
    /// `op(prev[w][i], c[w][i])` — two REAL operands so the reference, the
    /// kernel, and the emitted algo all agree (passing `prev` as both args
    /// would be degenerate for sub/xor/min/max).
    c: Vec<i32>,
}

impl PartitionWorkers {
    pub(crate) fn generate(rng: &mut Rng) -> PartitionWorkers {
        // 2..=4 compute workers (the curated corpus uses 4); keep small so
        // the 7 backend builds stay cheap. ps modest but >1.
        let nw = rng.range(2, 4) as usize;
        let ps = rng.range(2, 32) as usize;
        let n_stages = rng.range(1, 3) as usize;
        let stages: Vec<Op> = (0..n_stages).map(|_| Op::random(rng)).collect();
        let a: Vec<i32> = (0..nw * ps).map(|_| rng.i32_value()).collect();
        let c: Vec<i32> = (0..nw * ps).map(|_| rng.i32_value()).collect();
        PartitionWorkers {
            nw,
            ps,
            stages,
            a,
            c,
        }
    }

    pub(crate) fn describe(&self) -> String {
        let mut s = format!(
            "partition_workers NW={} PS={} stages=[",
            self.nw, self.ps
        );
        for (i, op) in self.stages.iter().enumerate() {
            if i > 0 {
                s.push_str(", ");
            }
            s.push_str(&op.kernel_body());
        }
        s.push(']');
        s
    }

    /// Reference: fold the stage pipeline over element `x` against the
    /// SAME element `cv` of the second operand at each stage — mirroring
    /// the emitted `stage_k(prev[w][i], c[w][i])`. Each stage k:
    /// `x = op_k(x, cv)`.
    fn map_one(&self, mut x: i32, cv: i32) -> i32 {
        for op in &self.stages {
            x = op.apply(x, cv);
        }
        x
    }

    fn reference(&self) -> Vec<u8> {
        let mut bytes = Vec::with_capacity(self.a.len() * 4);
        let mapped: Vec<i32> = self
            .a
            .iter()
            .zip(self.c.iter())
            .map(|(&x, &cv)| self.map_one(x, cv))
            .collect();
        push_i32_le(&mut bytes, &mapped);
        bytes
    }

    fn input(&self) -> Vec<u8> {
        // a then c, both NW*PS words (same two-operand layout as the
        // 1-D pipeline's a/b).
        let mut bytes = Vec::with_capacity(self.a.len() * 8);
        push_i32_le(&mut bytes, &self.a);
        push_i32_le(&mut bytes, &self.c);
        bytes
    }

    fn algo_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "// GENERATED by diff_fuzz (seed={seed}). Multi-worker partition=workers map."
        );
        let _ = writeln!(s, "const NW : usize = {};", self.nw);
        let _ = writeln!(s, "const PS : usize = {};", self.ps);
        let _ = writeln!(s);
        let _ = writeln!(s, "data a : i32[NW][PS];");
        let _ = writeln!(s, "data c : i32[NW][PS];");
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "data r{i} : i32[NW][PS];");
        }
        let _ = writeln!(s);
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "kernel stage{i} : (i32, i32) -> i32 pure;");
        }
        let _ = writeln!(
            s,
            "kernel load_input  : ()             -> i32[NW][PS] effectful;"
        );
        let _ = writeln!(
            s,
            "kernel load_c      : ()             -> i32[NW][PS] effectful;"
        );
        let _ = writeln!(
            s,
            "kernel save_output : (i32[NW][PS])  -> ()          effectful;"
        );
        let _ = writeln!(s);
        let _ = writeln!(s, "a <-- load_input();");
        let _ = writeln!(s, "c <-- load_c();");
        let _ = writeln!(s);
        for i in 0..self.stages.len() {
            let src = if i == 0 {
                "a".to_string()
            } else {
                format!("r{}", i - 1)
            };
            let _ = writeln!(s, "for w : 0 .. NW {{");
            let _ = writeln!(s, "    for i : 0 .. PS {{");
            let _ = writeln!(s, "        r{i}[w][i] <-- stage{i}({src}[w][i], c[w][i]);");
            let _ = writeln!(s, "    }}");
            let _ = writeln!(s, "}}");
        }
        let _ = writeln!(s);
        let _ = writeln!(s, "save_output(r{});", self.stages.len() - 1);
        s
    }

    fn output_array(&self) -> String {
        format!("r{}", self.stages.len() - 1)
    }

    fn sched_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(
            s,
            "// {}-compute-worker partition=workers map, modelled on 03-reduction distributed.",
            self.nw
        );
        let _ = write!(s, "schedule for \"./prog.algo.nuc\" {{\n    workers = {{ host");
        for w in 0..self.nw {
            let _ = write!(s, ", w{w}");
        }
        let _ = writeln!(s, " }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    place load_input  on host;");
        let _ = writeln!(s, "    place load_c      on host;");
        let _ = writeln!(s, "    place save_output on host;");
        // Place every stage on the compute-worker set.
        let worker_set = (0..self.nw)
            .map(|w| format!("w{w}"))
            .collect::<Vec<_>>()
            .join(", ");
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "    place stage{i}        on {{ {worker_set} }};");
        }
        let _ = writeln!(s);
        let _ = writeln!(s, "    // Outer w-loop is the partition axis; one row per worker.");
        let _ = writeln!(s, "    loop w : partition=workers;");
        let _ = writeln!(s);
        // a and c cross host->workers; the final output crosses
        // workers->host. Intermediate stage arrays stay on the worker set.
        let _ = writeln!(s, "    transfer a : sync;");
        let _ = writeln!(s, "    transfer c : sync;");
        let _ = writeln!(s, "    transfer {} : sync;", self.output_array());
        let _ = writeln!(s, "}}");
        s
    }

    fn kernels_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(s, "use std::env;");
        let _ = writeln!(s, "use std::fs;");
        let _ = writeln!(s, "use std::io::Write;");
        let _ = writeln!(s);
        let _ = writeln!(s, "const NW: usize = {};", self.nw);
        let _ = writeln!(s, "const PS: usize = {};", self.ps);
        let _ = writeln!(s);
        for (i, op) in self.stages.iter().enumerate() {
            let _ = writeln!(s, "pub fn stage{i}(a: i32, b: i32) -> i32 {{");
            let _ = writeln!(s, "    {}", op.kernel_body());
            let _ = writeln!(s, "}}");
            let _ = writeln!(s);
        }
        // load_input reads a at [0, NW*PS); load_c reads c at [NW*PS, 2*NW*PS).
        let _ = writeln!(s, "pub fn load_input() -> Vec<i32> {{");
        let _ = writeln!(
            s,
            "    let path = env::var(\"NUC_INPUT_PATH\").unwrap_or_else(|_| \"input.bin\".to_string());"
        );
        let _ = writeln!(s, "    read_i32_le_slice(&path, 0, NW * PS)");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        let _ = writeln!(s, "pub fn load_c() -> Vec<i32> {{");
        let _ = writeln!(
            s,
            "    let path = env::var(\"NUC_INPUT_PATH\").unwrap_or_else(|_| \"input.bin\".to_string());"
        );
        let _ = writeln!(s, "    read_i32_le_slice(&path, NW * PS, NW * PS)");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        s.push_str(&io_scaffold::emit_save("NW * PS"));
        s.push_str(&io_scaffold::emit_read_helper());
        s
    }

    pub(crate) fn bundle(&self, seed: u64) -> SourceBundle {
        SourceBundle {
            algo: self.algo_src(seed),
            sched: self.sched_src(seed),
            kernels: self.kernels_src(seed),
            input: self.input(),
            reference: self.reference(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reference_folds_stages_against_second_operand() {
        // stage0 = add, stage1 = min, second operand c.
        // map(a=3, c=10): (3+10)=13 -> min(13,10)=10
        // map(a=-1,c=2):  (-1+2)=1 -> min(1,2)=1
        // map(a=5, c=-4): (5-4)=1  -> min(1,-4)=-4
        // map(a=-4,c=0):  (-4+0)=-4 -> min(-4,0)=-4
        let prog = PartitionWorkers {
            nw: 2,
            ps: 2,
            stages: vec![Op::WrappingAdd, Op::Min],
            a: vec![3, -1, 5, -4],
            c: vec![10, 2, -4, 0],
        };
        let mut want = Vec::new();
        push_i32_le(&mut want, &[10, 1, -4, -4]);
        assert_eq!(prog.reference(), want);
    }

    #[test]
    fn input_layout_is_a_then_c() {
        let prog = PartitionWorkers {
            nw: 1,
            ps: 2,
            stages: vec![Op::WrappingAdd],
            a: vec![1, 2],
            c: vec![3, 4],
        };
        let mut want = Vec::new();
        push_i32_le(&mut want, &[1, 2, 3, 4]);
        assert_eq!(prog.input(), want);
    }

    #[test]
    fn sched_places_all_stages_on_worker_set_and_partitions() {
        let prog = PartitionWorkers {
            nw: 3,
            ps: 4,
            stages: vec![Op::WrappingAdd],
            a: vec![0; 12],
            c: vec![0; 12],
        };
        let sched = prog.sched_src(0);
        assert!(sched.contains("workers = { host, w0, w1, w2 };"));
        assert!(sched.contains("place stage0        on { w0, w1, w2 };"));
        assert!(sched.contains("loop w : partition=workers;"));
        // a in, c in, r0 out — exactly three transfers.
        assert_eq!(sched.matches("transfer").count(), 3);
    }

    #[test]
    fn output_array_is_last_stage() {
        let prog = PartitionWorkers {
            nw: 2,
            ps: 2,
            stages: vec![Op::WrappingAdd, Op::BitXor, Op::Max],
            a: vec![0; 4],
            c: vec![0; 4],
        };
        assert_eq!(prog.output_array(), "r2");
        assert!(prog.sched_src(0).contains("transfer r2 : sync;"));
    }
}
