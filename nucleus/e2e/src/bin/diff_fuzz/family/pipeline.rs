//! Family: 1-D elementwise integer pipeline (host + w0 split).
//!
//! The original TASK-0453.01 shape, modelled on `02-split-add`. A random
//! array length `N`, a 1..=4-stage pipeline of pure scalar ops. Stage 0
//! reads inputs `a` and `b`; each later stage reads the previous stage's
//! output and `b`. A `host + w0` split with one `sync` transfer per
//! crossing data symbol. The compute loops cross a REAL worker boundary,
//! so the differential is meaningful. 7-backend.

use std::fmt::Write as _;

use super::io_scaffold;
use crate::op::Op;
use crate::program::{push_i32_le, SourceBundle};
use crate::rng::Rng;

#[derive(Clone, Debug)]
pub(crate) struct Pipeline1d {
    n: usize,
    /// One op per pipeline stage. `stages.len() >= 1`.
    stages: Vec<Op>,
    a: Vec<i32>,
    b: Vec<i32>,
}

impl Pipeline1d {
    pub(crate) fn generate(rng: &mut Rng) -> Pipeline1d {
        let n = rng.range(8, 512) as usize;
        let n_stages = rng.range(1, 4) as usize;
        let stages: Vec<Op> = (0..n_stages).map(|_| Op::random(rng)).collect();
        let a: Vec<i32> = (0..n).map(|_| rng.i32_value()).collect();
        let b: Vec<i32> = (0..n).map(|_| rng.i32_value()).collect();
        Pipeline1d { n, stages, a, b }
    }

    fn stage_out(&self, i: usize) -> String {
        format!("s{i}")
    }

    fn output_array(&self) -> String {
        self.stage_out(self.stages.len() - 1)
    }

    pub(crate) fn describe(&self) -> String {
        let mut s = format!("pipeline1d N={} stages=[", self.n);
        for (i, op) in self.stages.iter().enumerate() {
            if i > 0 {
                s.push_str(", ");
            }
            s.push_str(&op.kernel_body());
        }
        s.push(']');
        s
    }

    /// Reference oracle. Stage 0: `s0[i] = op0(a[i], b[i])`; stage k>0:
    /// `sk[i] = opk(s{k-1}[i], b[i])`.
    fn reference(&self) -> Vec<u8> {
        let mut prev = self.a.clone();
        for op in &self.stages {
            let mut cur = vec![0i32; self.n];
            for i in 0..self.n {
                cur[i] = op.apply(prev[i], self.b[i]);
            }
            prev = cur;
        }
        let mut bytes = Vec::with_capacity(self.n * 4);
        push_i32_le(&mut bytes, &prev);
        bytes
    }

    fn input(&self) -> Vec<u8> {
        let mut bytes = Vec::with_capacity(self.n * 8);
        push_i32_le(&mut bytes, &self.a);
        push_i32_le(&mut bytes, &self.b);
        bytes
    }

    fn algo_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "// GENERATED by diff_fuzz (seed={seed}). 1-D elementwise integer pipeline."
        );
        let _ = writeln!(s, "const N : usize = {};", self.n);
        let _ = writeln!(s);
        let _ = writeln!(s, "data a : i32[N];");
        let _ = writeln!(s, "data b : i32[N];");
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "data {} : i32[N];", self.stage_out(i));
        }
        let _ = writeln!(s);
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "kernel stage{i} : (i32, i32) -> i32 pure;");
        }
        let _ = writeln!(s, "kernel load_input   : ()       -> i32[N] effectful;");
        let _ = writeln!(s, "kernel load_input_b : ()       -> i32[N] effectful;");
        let _ = writeln!(s, "kernel save_output  : (i32[N]) -> ()     effectful;");
        let _ = writeln!(s);
        let _ = writeln!(s, "a <-- load_input();");
        let _ = writeln!(s, "b <-- load_input_b();");
        let _ = writeln!(s);
        for i in 0..self.stages.len() {
            let src = if i == 0 {
                "a".to_string()
            } else {
                self.stage_out(i - 1)
            };
            let _ = writeln!(s, "for i : 0 .. N {{");
            let _ = writeln!(s, "    {}[i] <-- stage{i}({src}[i], b[i]);", self.stage_out(i));
            let _ = writeln!(s, "}}");
        }
        let _ = writeln!(s);
        let _ = writeln!(s, "save_output({});", self.output_array());
        s
    }

    fn sched_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(s, "// host + w0 split, modelled on 02-split-add.");
        let _ = writeln!(s, "schedule for \"./prog.algo.nuc\" {{");
        let _ = writeln!(s, "    workers = {{ host, w0 }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    place load_input    on host;");
        let _ = writeln!(s, "    place load_input_b  on host;");
        let _ = writeln!(s, "    place save_output   on host;");
        for i in 0..self.stages.len() {
            let _ = writeln!(s, "    place stage{i}        on w0;");
        }
        let _ = writeln!(s);
        // One transfer per crossing data symbol: a, b (host->w0) and the
        // final output array (w0->host). Intermediate stage arrays stay on
        // w0 and must NOT carry a transfer.
        let _ = writeln!(s, "    transfer a : sync;");
        let _ = writeln!(s, "    transfer b : sync;");
        let _ = writeln!(s, "    transfer {} : sync;", self.output_array());
        let _ = writeln!(s, "}}");
        s
    }

    fn kernels_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        s.push_str(&io_scaffold::kernels_header(self.n));
        for (i, op) in self.stages.iter().enumerate() {
            let _ = writeln!(s, "pub fn stage{i}(a: i32, b: i32) -> i32 {{");
            let _ = writeln!(s, "    {}", op.kernel_body());
            let _ = writeln!(s, "}}");
            let _ = writeln!(s);
        }
        s.push_str(&io_scaffold::emit_load("load_input", "0", "N"));
        s.push_str(&io_scaffold::emit_load("load_input_b", "N", "N"));
        s.push_str(&io_scaffold::emit_save("N"));
        s.push_str(&io_scaffold::emit_read_helper());
        s
    }

    pub(crate) fn bundle(&self, seed: u64) -> SourceBundle {
        SourceBundle {
            algo: self.algo_src(seed),
            sched: self.sched_src(seed),
            kernels: self.kernels_src(seed),
            input: self.input(),
            reference: self.reference(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reference_matches_staged_pipeline() {
        // Two-stage: s0 = a+b, s1 = s0 max b.
        let prog = Pipeline1d {
            n: 3,
            stages: vec![Op::WrappingAdd, Op::Max],
            a: vec![1, 2, 3],
            b: vec![10, -5, 0],
        };
        // s0 = [11,-3,3]; s1 = [max(11,10),max(-3,-5),max(3,0)] = [11,-3,3].
        let mut want = Vec::new();
        push_i32_le(&mut want, &[11, -3, 3]);
        assert_eq!(prog.reference(), want);
    }

    #[test]
    fn single_stage_output_is_s0_and_three_transfers() {
        let prog = Pipeline1d {
            n: 1,
            stages: vec![Op::BitOr],
            a: vec![0],
            b: vec![0],
        };
        assert_eq!(prog.output_array(), "s0");
        let sched = prog.sched_src(0);
        assert!(sched.contains("transfer s0 : sync;"));
        // a, b, s0 — intermediate arrays get no transfer.
        assert_eq!(sched.matches("transfer").count(), 3);
    }

    #[test]
    fn input_layout_is_a_then_b() {
        let prog = Pipeline1d {
            n: 2,
            stages: vec![Op::WrappingAdd],
            a: vec![1, 2],
            b: vec![3, 4],
        };
        let mut want = Vec::new();
        push_i32_le(&mut want, &[1, 2, 3, 4]);
        assert_eq!(prog.input(), want);
    }
}
