//! Family: partitioned binned reduction over a combine operator.
//!
//! Modelled EXACTLY on 26-bin-min / 25-bin-parity / 08-histogram
//! distributed: a masked per-bin fold partitioned across compute workers
//! with `partition=workers`, each worker whole-array-replicating the
//! `result` accumulator (pre-init = the combine op's IDENTITY), and the
//! host element-wise combining the per-worker partials. Because every
//! combine op here is associative + commutative, the distributed fold is
//! order-independent and byte-identical to the sequential reference across
//! all 7 tier-1 backends (PRD §10.1).
//!
//! This family covers ALL SIX combine operators (sum, or, xor, and, min,
//! max) and the two identity-element edge cases the task names:
//!   * EMPTY BINS — a bin no input maps to retains the identity; the
//!     generator deliberately leaves at least one bin empty (BINS may
//!     exceed the distinct keys), exercising the identity pre-init.
//!   * MIN IDENTITY = TYPE MAX (and MAX = type MIN, AND = all-ones) — the
//!     non-zero identities (TASK-0343.01.02) that a 0-init backend would
//!     get wrong; the generated `val` values are biased so a wrong init
//!     diverges (see [`Reduction::generate`]).

use std::fmt::Write as _;

use super::io_scaffold;
use crate::op::CombineOp;
use crate::program::{push_i32_le, SourceBundle};
use crate::rng::Rng;

#[derive(Clone, Debug)]
pub(crate) struct Reduction {
    n: usize,
    bins: usize,
    op: CombineOp,
    /// Per-input bin key in `[0, bins)`.
    key: Vec<i32>,
    /// Per-input value folded into its bin.
    val: Vec<i32>,
}

impl Reduction {
    pub(crate) fn generate(rng: &mut Rng) -> Reduction {
        let op = *rng.choice(&CombineOp::ALL);
        // Keep BINS small and N modest so the 7 builds stay cheap. BINS is
        // chosen so that — for a maximally-sensitive empty-bin test — at
        // least one bin is likely empty: keys are drawn from a SMALLER
        // active range than BINS roughly half the time.
        let bins = rng.range(2, 16) as usize;
        let n = rng.range(8, 256) as usize;
        // Active key range: sometimes the full BINS (dense), sometimes a
        // strict subset (guarantees empty bins). Either way keys stay in
        // [0, bins).
        let active = if rng.chance(1, 2) {
            // strict subset -> guarantees >=1 empty bin when active < bins.
            (rng.range(1, bins as u64) as usize).max(1)
        } else {
            bins
        };
        let key: Vec<i32> = (0..n).map(|_| (rng.range(0, (active - 1) as u64)) as i32).collect();
        // Values: bias by op so a wrong-identity init diverges.
        //   min  -> strictly POSITIVE (a 0-init would beat any positive).
        //   max  -> strictly NEGATIVE (a 0-init would beat any negative).
        //   and  -> set the high bits (a 0-init would zero them out).
        //   sum/or/xor -> any value (identity is 0, already correct).
        let val: Vec<i32> = (0..n)
            .map(|_| {
                let raw = rng.i32_value();
                match op {
                    CombineOp::Min => (raw & i32::MAX).max(1), // [1, i32::MAX]
                    CombineOp::Max => -((raw & i32::MAX).max(1)), // [i32::MIN+? , -1]
                    CombineOp::And => raw | (0xF000_0000u32 as i32), // high nibble set
                    CombineOp::Sum | CombineOp::Or | CombineOp::Xor => raw,
                }
            })
            .collect();
        Reduction {
            n,
            bins,
            op,
            key,
            val,
        }
    }

    pub(crate) fn describe(&self) -> String {
        format!(
            "reduction op={} N={} BINS={}",
            self.op.name(),
            self.n,
            self.bins
        )
    }

    /// Reference oracle: per-bin fold with the op's identity pre-init.
    fn reference(&self) -> Vec<u8> {
        let id = self.op.identity();
        let mut result = vec![id; self.bins];
        for i in 0..self.n {
            let b = self.key[i] as usize;
            // The masked fold: only the matching bin combines this value.
            // (Reference mirrors the kernel `if k == bin { combine(acc, v) }`.)
            result[b] = self.op.apply(result[b], self.val[i]);
        }
        let mut bytes = Vec::with_capacity(self.bins * 4);
        push_i32_le(&mut bytes, &result);
        bytes
    }

    fn input(&self) -> Vec<u8> {
        let mut bytes = Vec::with_capacity(self.n * 8);
        push_i32_le(&mut bytes, &self.key);
        push_i32_le(&mut bytes, &self.val);
        bytes
    }

    fn algo_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "// GENERATED by diff_fuzz (seed={seed}). Binned {}-reduction, partition=workers.",
            self.op.name()
        );
        let _ = writeln!(s, "const N    : usize = {};", self.n);
        let _ = writeln!(s, "const BINS : usize = {};", self.bins);
        let _ = writeln!(s);
        let _ = writeln!(s, "data key    : i32[N];");
        let _ = writeln!(s, "data val    : i32[N];");
        let _ = writeln!(s, "data result : i32[BINS];");
        let _ = writeln!(s);
        let _ = writeln!(s, "kernel load_key    : ()          -> i32[N]    effectful;");
        let _ = writeln!(s, "kernel load_val    : ()          -> i32[N]    effectful;");
        let _ = writeln!(s, "kernel save_output : (i32[BINS]) -> ()        effectful;");
        // The combine= attribute drives the identity-aware accumulator
        // pre-init across all 7 backends (TASK-0343.01.01/.02).
        let _ = writeln!(
            s,
            "kernel bin_op      : (i32, i32, i32, i32) -> i32   pure combine={};",
            self.op.name()
        );
        let _ = writeln!(s);
        let _ = writeln!(s, "key <-- load_key();");
        let _ = writeln!(s, "val <-- load_val();");
        let _ = writeln!(s);
        let _ = writeln!(s, "for i : 0 .. N {{");
        let _ = writeln!(s, "    for b : 0 .. BINS {{");
        let _ = writeln!(s, "        result[b] <-- bin_op(result[b], key[i], val[i], b);");
        let _ = writeln!(s, "    }}");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        let _ = writeln!(s, "save_output(result);");
        s
    }

    fn sched_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(
            s,
            "// 4-worker i-band partition=workers reduction, modelled on 26-bin-min distributed."
        );
        let _ = writeln!(s, "schedule for \"./prog.algo.nuc\" {{");
        let _ = writeln!(s, "    workers = {{ host, w0, w1, w2, w3 }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    place load_key    on host;");
        let _ = writeln!(s, "    place load_val    on host;");
        let _ = writeln!(s, "    place save_output on host;");
        let _ = writeln!(s, "    place bin_op      on {{ w0, w1, w2, w3 }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    loop i : partition=workers;");
        let _ = writeln!(s);
        let _ = writeln!(s, "    transfer key    : sync;");
        let _ = writeln!(s, "    transfer val    : sync;");
        let _ = writeln!(s, "    transfer result : sync;");
        let _ = writeln!(s, "}}");
        s
    }

    fn kernels_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(s, "use std::env;");
        let _ = writeln!(s, "use std::fs;");
        let _ = writeln!(s, "use std::io::Write;");
        let _ = writeln!(s);
        let _ = writeln!(s, "const N: usize = {};", self.n);
        let _ = writeln!(s, "const BINS: usize = {};", self.bins);
        let _ = writeln!(s);
        // The masked fold kernel: combine(acc, v) iff k == bin, else acc.
        // The combine expression uses the SAME op as the combine= attr, so
        // the per-element fold and the host cross-worker combine agree.
        let _ = writeln!(s, "pub fn bin_op(acc: i32, k: i32, v: i32, bin: i32) -> i32 {{");
        let _ = writeln!(s, "    if k == bin {{");
        let _ = writeln!(s, "        {}", combine_acc_v_expr(self.op));
        let _ = writeln!(s, "    }} else {{");
        let _ = writeln!(s, "        acc");
        let _ = writeln!(s, "    }}");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        s.push_str(&io_scaffold::emit_load("load_key", "0", "N"));
        s.push_str(&io_scaffold::emit_load("load_val", "N", "N"));
        s.push_str(&io_scaffold::emit_save("BINS"));
        s.push_str(&io_scaffold::emit_read_helper());
        s
    }

    pub(crate) fn bundle(&self, seed: u64) -> SourceBundle {
        SourceBundle {
            algo: self.algo_src(seed),
            sched: self.sched_src(seed),
            kernels: self.kernels_src(seed),
            input: self.input(),
            reference: self.reference(),
        }
    }
}

/// The `combine(acc, v)` Rust expression for the matched-bin branch, using
/// `acc` and `v` (the kernel's first and third params). This is the SAME
/// arithmetic as `CombineOp::apply(acc, v)` — the single source of truth is
/// the op variant (intent-coupled, same bound as the elementwise ops).
fn combine_acc_v_expr(op: CombineOp) -> String {
    match op {
        CombineOp::Sum => "acc.wrapping_add(v)".to_string(),
        CombineOp::Or => "acc | v".to_string(),
        CombineOp::Xor => "acc ^ v".to_string(),
        CombineOp::And => "acc & v".to_string(),
        CombineOp::Min => "acc.min(v)".to_string(),
        CombineOp::Max => "acc.max(v)".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run_ref(op: CombineOp, bins: usize, key: &[i32], val: &[i32]) -> Vec<i32> {
        let r = Reduction {
            n: key.len(),
            bins,
            op,
            key: key.to_vec(),
            val: val.to_vec(),
        };
        let bytes = r.reference();
        bytes
            .chunks_exact(4)
            .map(|c| i32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect()
    }

    #[test]
    fn min_reduction_empty_bin_is_type_max() {
        // bin 0 gets {5, 3}; bin 1 empty; bin 2 gets {9}.
        let out = run_ref(CombineOp::Min, 3, &[0, 0, 2], &[5, 3, 9]);
        assert_eq!(out, vec![3, i32::MAX, 9]);
    }

    #[test]
    fn max_reduction_empty_bin_is_type_min() {
        let out = run_ref(CombineOp::Max, 3, &[0, 0, 2], &[-5, -3, -9]);
        assert_eq!(out, vec![-3, i32::MIN, -9]);
    }

    #[test]
    fn and_reduction_empty_bin_is_all_ones() {
        let out = run_ref(CombineOp::And, 2, &[0], &[0b1010]);
        assert_eq!(out, vec![0b1010, -1]);
    }

    #[test]
    fn sum_reduction_folds_per_bin() {
        let out = run_ref(CombineOp::Sum, 2, &[0, 1, 0], &[10, 7, 5]);
        assert_eq!(out, vec![15, 7]);
    }

    #[test]
    fn xor_reduction_folds_per_bin() {
        let out = run_ref(CombineOp::Xor, 1, &[0, 0, 0], &[0b1100, 0b1010, 0b0110]);
        // 1100 ^ 1010 = 0110; ^ 0110 = 0000.
        assert_eq!(out, vec![0]);
    }

    #[test]
    fn generated_min_values_are_positive() {
        // The min-bias must yield strictly-positive vals so an empty bin's
        // i32::MAX and a 0-init bug are distinguishable.
        let mut r = Rng::new(5);
        // Force the min op by sampling until we draw it (cheap).
        for s in 0..200u64 {
            let mut rr = Rng::new(s);
            let red = Reduction::generate(&mut rr);
            if red.op == CombineOp::Min {
                assert!(red.val.iter().all(|&v| v > 0), "min vals must be positive");
                return;
            }
        }
        let _ = &mut r;
        panic!("never drew a min reduction in 200 seeds");
    }

    #[test]
    fn kernel_uses_same_op_as_combine_attr() {
        let red = Reduction {
            n: 1,
            bins: 1,
            op: CombineOp::Min,
            key: vec![0],
            val: vec![1],
        };
        let k = red.kernels_src(0);
        assert!(k.contains("acc.min(v)"));
        let a = red.algo_src(0);
        assert!(a.contains("combine=min;"));
    }
}
