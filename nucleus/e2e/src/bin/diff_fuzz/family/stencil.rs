//! Family: 2-D vertical 3-point stencil forcing y-halo inference.
//!
//! Modelled on 05-stencil but with the load-bearing differences that keep
//! it 7-backend (05-stencil/distributed uses async/buffer/event transfers
//! only 4 backends support):
//!   * a VERTICAL 3-point stencil `out[y][x] = st3(in[y-1][x], in[y][x],
//!     in[y+1][x])` — the `y±1` reads are in the PARTITION AXIS, so the
//!     row-band partition genuinely FORCES halo inference (each worker's
//!     band needs the seam rows of its neighbours); and
//!   * `partition=rows` with PLAIN `sync` transfers, which every tier-1
//!     backend supports, so the cell is 7-backend bit-identical (verified
//!     by hand on pthreads-sync + mp-tcp-bufsync before landing).
//!
//! Boundary: the outer ring (`y == 0`, `y == H-1`) is NOT written and
//! stays at the single-assignment default 0 — the skip-with-zero policy
//! 05-stencil uses. The reference oracle replicates this exactly.
//!
//! Determinism / correctness: the stencil is a pure map of the input; the
//! row-band partition + halo strips reproduce the sequential result, so
//! the output is partition-count-invariant and equals the reference.

use std::fmt::Write as _;

use super::io_scaffold;
use crate::op::Op;
use crate::program::{push_i32_le, SourceBundle};
use crate::rng::Rng;

#[derive(Clone, Debug)]
pub(crate) struct Stencil2d {
    h: usize,
    w: usize,
    /// The reduction over the 3 vertical neighbours, expressed as a fold
    /// with a single op (applied left-to-right over the 3 taps). A pure
    /// associative-ish fold keeps the kernel a clean `(i32,i32,i32)->i32`.
    op: Op,
    /// Row-major grid, `h * w` words.
    grid: Vec<i32>,
}

impl Stencil2d {
    pub(crate) fn generate(rng: &mut Rng) -> Stencil2d {
        // H >= 6 so H-2 >= 4 — the interior row count is at least the
        // 4-worker count, keeping every worker's band non-empty (the
        // curated corpus tolerates empty bands too, but this keeps the
        // halo seams all real). W modest.
        let h = rng.range(6, 24) as usize;
        let w = rng.range(2, 16) as usize;
        // Use a SIMPLE two-arg op for the 3-tap fold (no affine: affine
        // ignores its second arg, which would make the stencil read only
        // one tap and defeat the halo point).
        let op = *rng.choice(&[
            Op::WrappingAdd,
            Op::WrappingSub,
            Op::WrappingMul,
            Op::BitAnd,
            Op::BitOr,
            Op::BitXor,
            Op::Min,
            Op::Max,
        ]);
        let grid: Vec<i32> = (0..h * w).map(|_| rng.i32_value()).collect();
        Stencil2d { h, w, op, grid }
    }

    pub(crate) fn describe(&self) -> String {
        format!(
            "stencil2d H={} W={} op={} (y-halo)",
            self.h,
            self.w,
            self.op.kernel_body()
        )
    }

    fn at(&self, y: usize, x: usize) -> i32 {
        self.grid[y * self.w + x]
    }

    /// Reference: interior `out[y][x] = fold(in[y-1][x], in[y][x],
    /// in[y+1][x])`; boundary ring stays 0. `fold(a,b,c) = op(op(a,b),c)`
    /// — the SAME left-fold the kernel emits.
    fn reference(&self) -> Vec<u8> {
        let mut out = vec![0i32; self.h * self.w];
        for y in 1..self.h - 1 {
            for x in 0..self.w {
                let a = self.at(y - 1, x);
                let b = self.at(y, x);
                let c = self.at(y + 1, x);
                out[y * self.w + x] = self.op.apply(self.op.apply(a, b), c);
            }
        }
        let mut bytes = Vec::with_capacity(out.len() * 4);
        push_i32_le(&mut bytes, &out);
        bytes
    }

    fn input(&self) -> Vec<u8> {
        let mut bytes = Vec::with_capacity(self.grid.len() * 4);
        push_i32_le(&mut bytes, &self.grid);
        bytes
    }

    fn algo_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "// GENERATED by diff_fuzz (seed={seed}). 2-D vertical 3-point stencil (y-halo)."
        );
        let _ = writeln!(s, "const H : usize = {};", self.h);
        let _ = writeln!(s, "const W : usize = {};", self.w);
        let _ = writeln!(s);
        let _ = writeln!(s, "data img_in  : i32[H][W];");
        let _ = writeln!(s, "data img_out : i32[H][W];");
        let _ = writeln!(s);
        let _ = writeln!(s, "kernel st3 : (i32, i32, i32) -> i32 pure;");
        let _ = writeln!(s, "kernel load_image : ()          -> i32[H][W] effectful;");
        let _ = writeln!(s, "kernel save_image : (i32[H][W]) -> ()        effectful;");
        let _ = writeln!(s);
        let _ = writeln!(s, "img_in <-- load_image();");
        let _ = writeln!(s);
        let _ = writeln!(s, "for y : 1 .. H-1 {{");
        let _ = writeln!(s, "for x : 0 .. W {{");
        let _ = writeln!(
            s,
            "    img_out[y][x] <-- st3(img_in[y-1][x], img_in[y][x], img_in[y+1][x]);"
        );
        let _ = writeln!(s, "}}}}");
        let _ = writeln!(s);
        let _ = writeln!(s, "save_image(img_out);");
        s
    }

    fn sched_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(
            s,
            "// 4-worker row-band partition=rows; y-halo strips; PLAIN sync transfers (7-backend)."
        );
        let _ = writeln!(s, "schedule for \"./prog.algo.nuc\" {{");
        let _ = writeln!(s, "    workers = {{ host, w0, w1, w2, w3 }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    place load_image on host;");
        let _ = writeln!(s, "    place save_image on host;");
        let _ = writeln!(s, "    place st3        on {{ w0, w1, w2, w3 }};");
        let _ = writeln!(s);
        let _ = writeln!(s, "    // Outer y-loop: row-band partition; st3's y±1 reads force halo.");
        let _ = writeln!(s, "    loop y : partition=rows;");
        let _ = writeln!(s);
        let _ = writeln!(s, "    transfer img_in  : sync;");
        let _ = writeln!(s, "    transfer img_out : sync;");
        let _ = writeln!(s, "}}");
        s
    }

    fn kernels_src(&self, seed: u64) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// GENERATED by diff_fuzz (seed={seed}).");
        let _ = writeln!(s, "use std::env;");
        let _ = writeln!(s, "use std::fs;");
        let _ = writeln!(s, "use std::io::Write;");
        let _ = writeln!(s);
        let _ = writeln!(s, "const H: usize = {};", self.h);
        let _ = writeln!(s, "const W: usize = {};", self.w);
        let _ = writeln!(s);
        // st3(a,b,c) = op(op(a,b), c). The op's kernel_body is written for
        // (a,b); we apply it twice with renamed temporaries to keep the
        // single-source-of-truth op.
        let _ = writeln!(s, "pub fn st3(a: i32, b: i32, c: i32) -> i32 {{");
        let _ = writeln!(s, "    let ab = {{ {} }};", self.op.kernel_body());
        // second application: op(ab, c). Reuse the body with a=ab, b=c by
        // emitting an inline closure-free re-binding.
        let _ = writeln!(s, "    let a = ab; let b = c;");
        let _ = writeln!(s, "    {}", self.op.kernel_body());
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        // load_image reads H*W words flat.
        let _ = writeln!(s, "pub fn load_image() -> Vec<i32> {{");
        let _ = writeln!(
            s,
            "    let path = env::var(\"NUC_INPUT_PATH\").unwrap_or_else(|_| \"input.bin\".to_string());"
        );
        let _ = writeln!(s, "    read_i32_le_slice(&path, 0, H * W)");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        // save_image: H*W words.
        let _ = writeln!(s, "pub fn save_image(data: Vec<i32>) {{");
        let _ = writeln!(s, "    assert_eq!(data.len(), H * W);");
        let _ = writeln!(
            s,
            "    let path = env::var(\"NUC_OUTPUT_PATH\").unwrap_or_else(|_| \"output.bin\".to_string());"
        );
        let _ = writeln!(s, "    let mut bytes = Vec::with_capacity(data.len() * 4);");
        let _ = writeln!(s, "    for v in &data {{");
        let _ = writeln!(s, "        bytes.extend_from_slice(&v.to_le_bytes());");
        let _ = writeln!(s, "    }}");
        let _ = writeln!(
            s,
            "    let mut f = fs::File::create(&path).expect(\"create output\");"
        );
        let _ = writeln!(s, "    f.write_all(&bytes).expect(\"write output\");");
        let _ = writeln!(s, "}}");
        let _ = writeln!(s);
        s.push_str(&io_scaffold::emit_read_helper());
        s
    }

    pub(crate) fn bundle(&self, seed: u64) -> SourceBundle {
        SourceBundle {
            algo: self.algo_src(seed),
            sched: self.sched_src(seed),
            kernels: self.kernels_src(seed),
            input: self.input(),
            reference: self.reference(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reference_writes_interior_and_zeros_the_ring() {
        // 4x2 grid, op = add. Interior rows are 1,2.
        let prog = Stencil2d {
            h: 4,
            w: 2,
            op: Op::WrappingAdd,
            grid: vec![1, 2, 3, 4, 5, 6, 7, 8],
        };
        // row1[x=0] = g[0][0]+g[1][0]+g[2][0] = 1+3+5 = 9
        // row1[x=1] = 2+4+6 = 12
        // row2[x=0] = 3+5+7 = 15 ; row2[x=1] = 4+6+8 = 18
        let out: Vec<i32> = prog
            .reference()
            .chunks_exact(4)
            .map(|c| i32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect();
        assert_eq!(out, vec![0, 0, 9, 12, 15, 18, 0, 0]);
    }

    #[test]
    fn stencil_reads_y_neighbours_in_partition_axis() {
        let prog = Stencil2d {
            h: 8,
            w: 4,
            op: Op::Max,
            grid: vec![0; 32],
        };
        let algo = prog.algo_src(0);
        assert!(algo.contains("img_in[y-1][x]"));
        assert!(algo.contains("img_in[y+1][x]"));
        let sched = prog.sched_src(0);
        assert!(sched.contains("loop y : partition=rows;"));
        // sync transfers only — no async/event (keeps it 7-backend).
        assert!(!sched.contains("async"));
        assert!(!sched.contains("notify=event"));
    }

    #[test]
    fn kernel_folds_three_taps_with_one_op() {
        let prog = Stencil2d {
            h: 6,
            w: 2,
            op: Op::Min,
            grid: vec![0; 12],
        };
        let k = prog.kernels_src(0);
        // min appears twice (once per fold application).
        assert!(k.matches("a.min(b)").count() >= 2);
    }
}
